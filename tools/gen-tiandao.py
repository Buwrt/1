def check(fp_path):
    if not fp_path or not os.path.isfile(fp_path):
        print('[检测] 未提供参考词典，跳过重合检测')
        return
    fp = json.load(open(fp_path))
    vals = set(v.strip() for v in fp.values())
    bad = ([('TERMS.' + k, v) for k, v in TERMS.items() if v in vals]
           + [('EXACT.' + k, v) for k, v in EXACT.items() if v in vals]
           + [('KEYS.' + k, v) for k, v in KEYS.items() if v in vals])
    if bad:
        print('[检测] ✗ 有 %d 条与参考词典相同，必须重写：' % len(bad))
        for k, v in bad:
            print('       %-28s -> %s' % (k, v))
        raise SystemExit(1)
    print('[检测] ✓ 与参考词典 %d 条译法零重合' % len(vals))


def esc(s):
    return s.replace('\\', '\\\\').replace("'", "\\'")


def dump(name, d):
    """输出一段 JS 对象。键按长度降序 —— 运行时长词优先替换。"""
    items = sorted(d.items(), key=lambda kv: (-len(kv[0]), kv[0]))
    out = ['  window.%s = {' % name]
    for i, (k, v) in enumerate(items):
        out.append("    '%s': '%s'%s" % (esc(k), esc(v),
                                         ',' if i < len(items) - 1 else ''))
    out.append('  };')
    return out


