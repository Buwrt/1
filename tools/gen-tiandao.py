# ═══════════════════════════════════════════════════════════════
# 三、重合检测：与 FolkPatch zh-WC 词典逐条比对
# ═══════════════════════════════════════════════════════════════
def check(fp_path):
    if not fp_path or not os.path.isfile(fp_path):
        print('[检测] 未提供 FolkPatch 词典，跳过重合检测')
        return
    fp = json.load(open(fp_path))
    fp_vals = set(v.strip() for v in fp.values())
    bad = [(k, v) for k, v in S.items() if v in fp_vals]
    bad += [('[key]' + k, v) for k, v in K.items() if v in fp_vals]
    if bad:
        print('[检测] ✗ 仍有 %d 条与 FolkPatch 相同，必须重写：' % len(bad))
        for k, v in bad:
            print('       %-24s -> %s' % (k, v))
        raise SystemExit(1)
    print('[检测] ✓ 与 FolkPatch 词典 %d 条译法零重合' % len(fp_vals))

